#!/usr/bin/env python3
"""CLI entry point for combining every warning-free RULE block (scripts/build_rule.py's rule.txt
output) into one file, ready to paste into (or append onto) an antiSMASH rule file.

Skips any group whose rule.txt carries a '# WARNING' comment -- those need manual review first
(see rule_conditions.md for the detail behind each warning) -- and any rule dropped in
data/manual_rules.tsv ('# DROPPED').

By default the output carries a generated header and the '# MANUAL' note above each hand-written
rule; --no-comments leaves both out, for a file of nothing but RULE blocks.
"""

import argparse
import re
import sys
from pathlib import Path

DEFAULT_SEGMENTS_DIR = Path(__file__).resolve().parent.parent / "output" / "segments"
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "output" / "subcluster_rules.txt"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--segments-dir", type=Path, default=DEFAULT_SEGMENTS_DIR,
                         help="Parent dir of per-group output dirs, each containing a rule.txt.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="Combined output file.")
    parser.add_argument("--no-comments", action="store_true",
                         help="Leave out the generated header and the '# MANUAL' notes, so the file holds "
                              "nothing but RULE blocks.")
    return parser.parse_args()


def strip_comment_lines(text: str) -> str:
    """Drop whole-line '#' comments (the '# MANUAL' notes build_rule.py writes above a block)."""
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))


def main() -> int:
    args = parse_args()
    rule_files = sorted(args.segments_dir.glob("*/rule.txt"))
    if not rule_files:
        print(f"error: no rule.txt files found under {args.segments_dir}", file=sys.stderr)
        return 1

    clean: list[str] = []
    skipped: list[str] = []
    dropped: list[str] = []
    for path in rule_files:
        text = path.read_text()
        if text.lstrip().startswith("# DROPPED"):
            dropped.append(path.parent.name)
        elif text.lstrip().startswith("# WARNING"):
            skipped.append(path.parent.name)
        else:
            clean.append((strip_comment_lines(text) if args.no_comments else text).strip())

    if not clean:
        print("error: every rule.txt has warnings -- nothing to combine", file=sys.stderr)
        return 1

    # A SUPERIORS id that names no rule in the combined file makes antiSMASH reject the whole
    # file, so catch it here rather than at load time.
    combined = "\n\n".join(clean)
    present = set(re.findall(r"(?m)^RULE\s+(\S+)", combined))
    dangling: list[tuple[str, str]] = []
    for block in re.split(r"(?m)^RULE\s+", combined)[1:]:
        rid = block.split()[0]
        for match in re.findall(r"(?m)^\s*SUPERIORS\s+(.+)$", block):
            for sup in (v.strip() for v in match.split(",")):
                if sup and sup not in present:
                    dangling.append((rid, sup))
    if dangling:
        print("error: SUPERIORS naming a rule that is not in the combined file:", file=sys.stderr)
        for rid, sup in dangling:
            print(f"  {rid}: SUPERIORS {sup}", file=sys.stderr)
        print("  (a dropped or warning-skipped superior must be removed from data/manual_rules.tsv)",
              file=sys.stderr)
        return 1

    try:
        segments_dir_display = args.segments_dir.relative_to(Path.cwd())
    except ValueError:
        segments_dir_display = args.segments_dir
    header = "" if args.no_comments else (
        f"# Auto-generated by scripts/combine_rules.py from {len(clean)} of {len(rule_files)} "
        f"rule.txt file(s) under {segments_dir_display} -- {len(skipped)} skipped for having warnings, "
        f"{len(dropped)} dropped in data/manual_rules.tsv.\n\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + "\n\n".join(clean) + "\n")

    print(f"{len(clean)} rule(s) written to {args.out}")
    if dropped:
        print(f"{len(dropped)} rule(s) dropped in data/manual_rules.tsv: {', '.join(dropped)}", file=sys.stderr)
    if skipped:
        print(f"{len(skipped)} rule(s) skipped (have warnings):", file=sys.stderr)
        for group_name in skipped:
            print(f"  {group_name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
